// Package policyprojection lowers the Gooo disposition and its native ID bridge.
package policyprojection

import (
	"context"
	"fmt"
	"go/format"
	"strings"

	"github.com/kimjooyoon/meta-ontology-go/internal/bodycodegen"
)

const ActivityID = "gooo://metric-operation-origin/describe-operation"
const RecordID = "gooo://metric-operation-origin/disposition-record"

type Output struct {
	Source []byte
	Report bodycodegen.Report
}

func Generate(filename string, source, nativeTarget []byte) (Output, error) {
	activity, err := sourceActivity(filename, source)
	if err != nil {
		return Output{}, err
	}
	generator, err := bodycodegen.NewTypedPathGenerator("")
	if err != nil {
		return Output{}, err
	}
	result, err := generator.GenerateSourceAssembly(context.Background(), filename, source, activity)
	if err != nil {
		return Output{}, err
	}
	r := result.Report.RecordAssembly
	if result.Report.ActivityID != ActivityID || r == nil || r.Status != "COMPLETE_FINITE" ||
		r.Total != 4 || r.Passed != 4 || r.FieldsTotal != 24 || r.FieldsPassed != 24 ||
		r.ModelRequested || r.ModelCalls != 0 || !result.Report.TypecheckPassed || !result.Report.DeterministicReplay {
		return Output{}, fmt.Errorf("policy requires its fixed four-input, six-field source contract")
	}
	adapter, err := renderAdapter(result.Report, nativeTarget)
	if err != nil {
		return Output{}, err
	}
	const prefix = "package unresolvedpolicy\n\n"
	marker := fmt.Sprintf("//gooo:generated:end id=%q kind=\"entity\"", RecordID)
	if !strings.HasPrefix(result.Source, prefix) || strings.Count(result.Source, marker) != 1 {
		return Output{}, fmt.Errorf("policy requires its declared package and one native record region")
	}
	combined := "// Code generated by metric-unresolved-policy-codegen; DO NOT EDIT.\n" +
		strings.Replace(result.Source, marker, adapter+marker, 1)
	projection, err := format.Source([]byte(combined))
	if err != nil {
		return Output{}, err
	}
	if err := checkNativeProjection(projection, nativeTarget); err != nil {
		return Output{}, err
	}
	return Output{Source: projection, Report: result.Report}, nil
}
