package unresolvedpolicy_test

import (
	"bytes"
	"go/format"
	"os"
	"strings"
	"testing"

	"github.com/kimjooyoon/meta-ontology-go/internal/bodycodegen"
	"github.com/kimjooyoon/meta-ontology-go/internal/meta/metricprogram/unresolvedpolicy"
)

func TestUnresolvedPolicyProjectionFresh1723(t *testing.T) {
	raw, err := os.ReadFile("policy.gooo")
	if err != nil {
		t.Fatal(err)
	}
	var combined strings.Builder
	combined.WriteString("// Code generated by metric-unresolved-policy-codegen; DO NOT EDIT.\npackage unresolvedpolicy\n\n")
	for _, name := range []string{"OperationResolution", "OperationReason", "OperationNextStep"} {
		result, err := bodycodegen.Generate("policy.gooo", raw, name)
		if err != nil {
			t.Fatal(err)
		}
		const prefix = "package unresolvedpolicy\n\n"
		if !strings.HasPrefix(result.Source, prefix) || result.Report.RouteDecision.Provider != "deterministic" {
			t.Fatal("policy source did not retain its deterministic package")
		}
		combined.WriteString(strings.TrimPrefix(result.Source, prefix))
		combined.WriteByte('\n')
	}
	expected, err := format.Source([]byte(combined.String()))
	if err != nil {
		t.Fatal(err)
	}
	actual, err := os.ReadFile("policy.generated.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(actual, expected) {
		t.Fatal("compiled policy projection differs from source")
	}
	if err := unresolvedpolicy.VerifyProjection(); err != nil {
		t.Fatal(err)
	}
}
