func TestSplitPreservesDeclaredPackageNamesInsteadOfDirectoryGuesses(t *testing.T) {
	for _, row := range []struct{ directory, declared string }{
		{"with-dash", "declared"}, {"display", "actual"}, {"versioned/v2", "api"},
	} {
		t.Run(row.directory, func(t *testing.T) {
			root := t.TempDir()
			write := func(name, content string) {
				t.Helper()
				path := filepath.Join(root, name)
				if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
					t.Fatal(err)
				}
			}
			write("go.mod", "module binding.test/root\n\ngo 1.27.3\n")
			write(row.directory+"/value.go", "package "+row.declared+"\ntype Number struct{Count int64}\nfunc Read(n Number) int64 {return n.Count}\n")
			source := fmt.Sprintf("package main\nimport \"binding.test/root/%s\"\nfunc Value() int64{return %s.Read(%s.Number{Count:17})}\n", row.directory, row.declared, row.declared)
			for index := range 80 {
				source += fmt.Sprintf("func F%d() int{return %d}\n", index, index)
			}
			write("main.go", source)
			write("main_test.go", "package main\nimport \"testing\"\nfunc TestValue(t *testing.T){if Value()!=17{t.Fatal(Value())}}\n")
			check := func() {
				t.Helper()
				command := exec.Command(filepath.Join(runtime.GOROOT(), "bin", "go"), "test", "-count=1", ".")
				command.Dir, command.Env = root, append(os.Environ(), "GOWORK=off", "GOTOOLCHAIN=local")
				if output, err := command.CombinedOutput(); err != nil {
					t.Fatal(err, string(output))
				}
			}
			check()
			generated, paths, err := Extract(root, "main.go")
			if err != nil || len(paths) < 2 {
				t.Fatal("source was not split", paths, err)
			}
			bound := false
			for name, raw := range generated {
				bound = bound || strings.Contains(string(raw), row.declared+" \"binding.test/root/"+row.directory+"\"")
				write(name, string(raw))
			}
			if !bound {
				t.Fatal("declared binding was not retained")
			}
			check()
		})
	}
}

func TestExplicitExtractionDeclinesGeneratorOwnedSource(t *testing.T) {
	root := t.TempDir()
	source := []byte("// Code generated by gooo; DO NOT EDIT.\npackage sample\nfunc Value()int{return 17}\n")
	if err := os.WriteFile(filepath.Join(root, "source.go"), source, 0o644); err != nil {
		t.Fatal(err)
	}
	result, err := ExtractWithResult(root, "source.go")
	if err == nil || !strings.Contains(err.Error(), "GENERATED_SOURCE_OWNER_REQUIRED") || len(result.Generated) != 0 {
		t.Fatal(result, err)
	}
	stored, readErr := os.ReadFile(filepath.Join(root, "source.go"))
	if readErr != nil || string(stored) != string(source) {
		t.Fatal("owned bytes changed", readErr)
	}
}
