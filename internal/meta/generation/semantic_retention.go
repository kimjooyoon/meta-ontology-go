func SemanticRetentionUnknownState(reason string) *EnvelopeUnknownState {
	step := SemanticRetentionUnknownCertificateStep
	blockedBy := "retained_certificate"
	if reason == SemanticRetentionUnknownAuthorizationReason {
		step = SemanticRetentionUnknownAuthorizationStep
		blockedBy = "retention_authorization"
	}
	return &EnvelopeUnknownState{
		Stage: SemanticRetentionUnknownStage, Step: step, Reason: reason,
		UnknownClass: SemanticRetentionUnknownClass, NextOperation: SemanticRetentionUnknownNext,
		BlockedBy: []string{blockedBy},
	}
}

func SameSemanticRetentionUnknown(left, right *EnvelopeUnknownState) bool {
	if left == nil || right == nil {
		return left == right
	}
	return left.Stage == right.Stage && left.Step == right.Step && left.Reason == right.Reason &&
		left.UnknownClass == right.UnknownClass && left.NextOperation == right.NextOperation &&
		strings.Join(left.BlockedBy, "\x00") == strings.Join(right.BlockedBy, "\x00")
}

func ValidateSemanticRetentionResult(result SemanticRetentionResult) error {
	if result.Schema != SemanticRetentionResultSchema || result.Lifecycle == "" ||
		result.CandidateStableID == "" || !cache.Digest(result.AdoptionReportDigest).Known() ||
		!cache.Digest(result.ObservationDigest).Known() || !cache.Digest(result.ProposalDigest).Known() ||
		!cache.Digest(result.ContractSourceDigest).Known() || !cache.Digest(result.InputSourceDigest).Known() ||
		!cache.Digest(result.EvaluatorDigest).Known() ||
		result.RepositoryWrites != 0 || result.LocalTestExecutions != 0 {
		return errors.New("semantic retention result is invalid")
	}
	switch result.Decision {
	case "UNKNOWN":
		if (result.Reason != SemanticRetentionUnknownCertificateReason && result.Reason != SemanticRetentionUnknownAuthorizationReason) ||
			!SameSemanticRetentionUnknown(result.Unknown, SemanticRetentionUnknownState(result.Reason)) ||
			result.CertificateDigest != "" || len(result.GeneratedSource) != 0 || result.NormalizedIRDigest != "" || result.GeneratedOutputDigest != "" ||
			result.Metrics != (SemanticRetentionRuntimeMetrics{}) {
			return errors.New("semantic retention UNKNOWN result is not causal")
		}
	case SemanticRetentionRefuted:
		if result.Reason != SemanticRetentionRefutedReason || result.Unknown != nil || len(result.GeneratedSource) != 0 ||
			result.NormalizedIRDigest != "" || result.GeneratedOutputDigest != "" || result.Metrics.SemanticOperationCount != 0 ||
			result.Metrics.CertificateHits != 0 || result.Metrics.CertificateMisses != 1 {
			return errors.New("semantic retention REFUTED result is not causal")
		}
	case "CLOSED":
		if result.Unknown != nil || len(result.GeneratedSource) == 0 || !cache.Digest(result.CertificateDigest).Known() ||
			!cache.Digest(result.NormalizedIRDigest).Known() || !cache.Digest(result.GeneratedOutputDigest).Known() ||
			cache.HashBytes(result.GeneratedSource).String() != result.GeneratedOutputDigest ||
			result.Metrics.SemanticOperationCount < 0 || result.Metrics.CertificateHits < 0 || result.Metrics.CertificateMisses < 0 {
			return errors.New("semantic retention CLOSED result is invalid")
		}
	default:
		return errors.New("semantic retention result decision is invalid")
	}
	return nil
}

// SemanticRetentionManifestDigest binds a certificate to exact source files
// instead of an implicit repository version or mutable process cache.
func SemanticRetentionManifestDigest(readFile func(string) ([]byte, error), paths []string) (string, error) {
	if readFile == nil {
		return "", errors.New("retention manifest reader is nil")
	}
	var builder strings.Builder
	for _, path := range paths {
		data, err := readFile(path)
		if err != nil {
			return "", fmt.Errorf("read retention manifest file %s: %w", path, err)
		}
		builder.WriteString(path)
		builder.WriteByte('\t')
		builder.WriteString(cache.HashBytes(data).String())
		builder.WriteByte('\n')
	}
	return cache.HashBytes([]byte(builder.String())).String(), nil
}

func SemanticRetentionCompilerDigest(readFile func(string) ([]byte, error)) (string, error) {
	return SemanticRetentionManifestDigest(readFile, semanticRetentionCompilerManifestPaths[:])
}

func SemanticRetentionVerifierDigest(readFile func(string) ([]byte, error)) (string, error) {
	return SemanticRetentionManifestDigest(readFile, semanticRetentionVerifierManifestPaths[:])
}

func SemanticRetentionToolchainDigest() string {
	return cache.HashBytes([]byte(strings.Join([]string{runtime.Version(), runtime.GOOS, runtime.GOARCH}, "\x00"))).String()
}

