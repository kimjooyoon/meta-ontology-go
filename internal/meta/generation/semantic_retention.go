// SemanticRetentionCertificate is an immutable, caller-owned result of an
// explicitly authorized compiler operation. It carries the generated bytes
// so a later process can consume the exact result without process memory.
type SemanticRetentionCertificate struct {
	Schema                  string `json:"schema"`
	CertificateID           string `json:"certificate_id"`
	AdoptionReportDigest    string `json:"adoption_report_digest"`
	ObservationDigest       string `json:"observation_digest"`
	ProposalDigest          string `json:"proposal_digest"`
	AuthorizationDigest     string `json:"authorization_digest"`
	CandidateStableID       string `json:"candidate_stable_id"`
	Target                  string `json:"target"`
	Mode                    string `json:"mode"`
	ContractSourceDigest    string `json:"contract_source_digest"`
	InputSourceDigest       string `json:"input_source_digest"`
	NormalizedIRDigest      string `json:"normalized_ir_digest"`
	GeneratedOutputDigest   string `json:"generated_output_digest"`
	CompilerDigest          string `json:"compiler_digest"`
	ToolchainDigest         string `json:"toolchain_digest"`
	VerifierDigest          string `json:"verifier_digest"`
	PolicyDigest            string `json:"policy_digest"`
	EvaluatorDigest         string `json:"evaluator_digest"`
	GeneratedSource         []byte `json:"generated_source"`
	GeneratedManifest       []byte `json:"generated_manifest"`
	GeneratedManifestDigest string `json:"generated_manifest_digest"`
	RepositoryWrites        int    `json:"repository_writes"`
	LocalTestExecutions     int    `json:"local_test_executions"`
}

// SemanticRetentionCertificateContentDigest derives the certificate identity
// without a self-referential field.
func SemanticRetentionCertificateContentDigest(certificate SemanticRetentionCertificate) (string, error) {
	certificate.CertificateID = ""
	digest, err := cache.DigestOf(certificate)
	if err != nil {
		return "", fmt.Errorf("retention certificate content digest: %w", err)
	}
	return digest.String(), nil
}

func ValidateSemanticRetentionCertificate(certificate SemanticRetentionCertificate) error {
	if certificate.Schema != SemanticRetentionCertificateSchema ||
		!cache.Digest(certificate.CertificateID).Known() ||
		certificate.Target != SemanticRetentionTarget || certificate.Mode != SemanticRetentionMode ||
		certificate.CandidateStableID == "" || len(certificate.GeneratedSource) == 0 || len(certificate.GeneratedManifest) == 0 ||
		certificate.RepositoryWrites != 0 || certificate.LocalTestExecutions != 0 {
		return errors.New("semantic retention certificate is invalid")
	}
	for _, value := range []string{
		certificate.AdoptionReportDigest, certificate.ObservationDigest, certificate.ProposalDigest,
		certificate.AuthorizationDigest, certificate.ContractSourceDigest, certificate.InputSourceDigest,
		certificate.NormalizedIRDigest, certificate.GeneratedOutputDigest, certificate.CompilerDigest,
		certificate.ToolchainDigest, certificate.VerifierDigest, certificate.PolicyDigest, certificate.EvaluatorDigest,
	} {
		if !cache.Digest(value).Known() {
			return errors.New("semantic retention certificate contains unknown digest evidence")
		}
	}
	if cache.HashBytes(certificate.GeneratedSource).String() != certificate.GeneratedOutputDigest {
		return errors.New("semantic retention certificate generated output digest does not match bytes")
	}
	if !cache.Digest(certificate.GeneratedManifestDigest).Known() ||
		cache.HashBytes(certificate.GeneratedManifest).String() != certificate.GeneratedManifestDigest {
		return errors.New("semantic retention certificate generated manifest digest does not match bytes")
	}
	contentDigest, err := SemanticRetentionCertificateContentDigest(certificate)
	if err != nil {
		return err
	}
	if contentDigest != certificate.CertificateID {
		return errors.New("semantic retention certificate identity is not content-addressed")
	}
	return nil
}

// SemanticRetentionBindings are recomputed by the later invocation and are
// compared field-for-field before any retained bytes are consumed.
type SemanticRetentionBindings struct {
	AdoptionReportDigest string
	ObservationDigest    string
	ProposalDigest       string
	AuthorizationDigest  string
	CandidateStableID    string
	ContractSourceDigest string
	InputSourceDigest    string
	NormalizedIRDigest   string
	CompilerDigest       string
	ToolchainDigest      string
	VerifierDigest       string
	PolicyDigest         string
	EvaluatorDigest      string
}

func VerifySemanticRetentionCertificate(certificate SemanticRetentionCertificate, expected SemanticRetentionBindings) error {
	if err := ValidateSemanticRetentionCertificate(certificate); err != nil {
		return err
	}
	actual := []string{
		certificate.AdoptionReportDigest, certificate.ObservationDigest, certificate.ProposalDigest,
		certificate.AuthorizationDigest, certificate.CandidateStableID, certificate.ContractSourceDigest,
		certificate.InputSourceDigest, certificate.NormalizedIRDigest, certificate.CompilerDigest,
		certificate.ToolchainDigest, certificate.VerifierDigest, certificate.PolicyDigest,
		certificate.EvaluatorDigest,
	}
	want := []string{
		expected.AdoptionReportDigest, expected.ObservationDigest, expected.ProposalDigest,
		expected.AuthorizationDigest, expected.CandidateStableID, expected.ContractSourceDigest,
		expected.InputSourceDigest, expected.NormalizedIRDigest, expected.CompilerDigest,
		expected.ToolchainDigest, expected.VerifierDigest, expected.PolicyDigest,
		expected.EvaluatorDigest,
	}
	for index := range actual {
		if actual[index] != want[index] {
			return errors.New("semantic retention certificate does not bind the exact current evidence")
		}
	}
	return nil
}

