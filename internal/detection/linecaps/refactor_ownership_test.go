package linecaps

import "testing"

func TestGeneratedOwnershipKeepsMeasurementsWithoutGoRewriteCandidates(t *testing.T) {
	function := "func Evaluate() int {\n value := 3\n return value\n}\n"
	for _, row := range []struct {
		name, source string
		writable     bool
	}{
		{"handwritten", "package p\n" + function, true},
		{"standard-marker", "// Code generated by another compiler; DO NOT EDIT.\npackage p\n" + function, false},
		{"gooo-region", "package p\n//gooo:generated:start id=\"urn:entry\" kind=\"library-entry\"\n" + function + "//gooo:generated:end id=\"urn:entry\" kind=\"library-entry\"\n", false},
		{"mixed-ownership", "package p\n//gooo:generated:start id=\"urn:entity\" kind=\"entity\"\ntype R int\n//gooo:generated:end id=\"urn:entity\" kind=\"entity\"\n" + function, false},
		{"legacy", "package p\n//gooo:generated begin entry\n" + function + "//gooo:generated end\n", false},
		{"incomplete-slot", "package p\n//gooo:slot:start id=\"urn:missing-owner\"\n" + function, false},
		{"marker-in-data", "package p\nconst text = `\n//gooo:generated:start id=\"data\"\n`\n" + function, true},
	} {
		t.Run(row.name, func(t *testing.T) {
			findings, err := AnalyzeSource("ordinary.go", []byte(row.source), Limits{MaxFileLines: 2, MaxFunctionLines: 2})
			if err != nil {
				t.Fatal(err)
			}
			if hasFinding(findings, RuleRefactorAssign) != row.writable {
				t.Fatal("wrong mutation ownership", findings)
			}
			if !hasFinding(findings, RuleFileLines) || !hasFinding(findings, RuleFunctionLines) {
				t.Fatal("generated size observations lost", findings)
			}
		})
	}
}
