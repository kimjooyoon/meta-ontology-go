package bodylibrary

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"go/types"
)

const maxLibraryProjectionBytes = 256 << 10

func renderLibraryProjection(fset *token.FileSet, file *ast.File, sourceDigest, planDigest string) (string, error) {
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by gooo package generate; DO NOT EDIT.\n// Lowered Gooo source: %s\n// Typed plan: %s\n\n", sourceDigest, planDigest)
	fmt.Fprintf(&out, "// Package %s exposes a source-defined Gooo computation through Evaluate.\n", file.Name.Name)
	if err := format.Node(&out, fset, file); err != nil {
		return "", err
	}
	return formatLibraryProjection(out.String())
}

func formatLibraryProjection(source string) (string, error) {
	if len(source) > maxLibraryProjectionBytes {
		return "", fmt.Errorf("library projection exceeds 256 KiB")
	}
	raw, err := format.Source([]byte(source))
	if err != nil {
		return "", err
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "library.go", raw, 0)
	if err != nil {
		return "", err
	}
	if _, err := new(types.Config).Check("gooo.library", fset, []*ast.File{file}, nil); err != nil {
		return "", fmt.Errorf("library projection typecheck: %w", err)
	}
	return string(raw), nil
}
