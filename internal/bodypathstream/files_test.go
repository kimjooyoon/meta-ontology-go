func fileArgs(t *testing.T, recipe bool, suite string) ([]string, string) {
	t.Helper()
	root := t.TempDir()
	fixture, activity := "typed-path-compound", "Combined"
	plan := "typed-path-compound-plan.json"
	if recipe {
		fixture, activity, plan = "path-recipe", "BuildTotal", "path-recipe.json"
	}
	source, err := os.ReadFile("../../examples/body-codegen/" + fixture + ".gooo.fixture")
	if err != nil {
		t.Fatal(err)
	}
	if recipe {
		source = bytes.ReplaceAll(source, []byte("Compose"), []byte(activity))
		raw, err := os.ReadFile("../../examples/body-codegen/" + plan)
		if err != nil {
			t.Fatal(err)
		}
		// The original one-case fixture permits multiple bodies. Add a declared
		// selection example; keep the separate runtime inputs unchanged.
		raw = bytes.Replace(raw, []byte(`{"input": 10, "expected": -3}`),
			[]byte(`{"input": 10, "expected": -3}, {"input": 0, "expected": 7}`), 1)
		plan = filepath.Join(root, "recipe.json")
		if err := os.WriteFile(plan, raw, 0644); err != nil {
			t.Fatal(err)
		}
	} else {
		plan = "../../examples/body-codegen/" + plan
	}
	if err := os.WriteFile(filepath.Join(root, "source.gooo"), source, 0644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "cases.json"), []byte(suite), 0644); err != nil {
		t.Fatal(err)
	}
	tool := filepath.Join(runtime.GOROOT(), "bin", "go")
	if runtime.GOOS == "windows" {
		tool += ".exe"
	}
	out := filepath.Join(root, "output")
	return []string{"--source", filepath.Join(root, "source.gooo"), "--activity", activity,
		"--path-plan", plan, "--cases", filepath.Join(root, "cases.json"),
		"--out", out, "--repeat", "2", "--go-bin", tool}, out
}

func fileSummary(t *testing.T, out string) []fileRunRow {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(out, "summary.json"))
	if err != nil {
		t.Fatal(err)
	}
	var summary struct {
		Schema string       `json:"schema"`
		Rows   []fileRunRow `json:"rows"`
	}
	if err := json.Unmarshal(b, &summary); err != nil || summary.Schema != "gooo/body-path-file-run/v1" {
		t.Fatal("invalid summary", err)
	}
	return summary.Rows
}

func TestFilesNamedActivitiesAndActualNativeReuse(t *testing.T) {
	for _, recipe := range []bool{false, true} {
		suite := `{"schema":"gooo/body-runtime-cases/v1","cases":[{"input":2,"expected":15},{"input":-4,"expected":-21}]}`
		if recipe {
			suite = `{"schema":"gooo/body-runtime-cases/v1","cases":[{"input":2,"expected":5},{"input":-4,"expected":11}]}`
		}
		args, out := fileArgs(t, recipe, suite)
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		var stdout, stderr bytes.Buffer
		code := RunFilesCommand(ctx, "files", args, &stdout, &stderr)
		cancel()
		if code != 0 {
			t.Fatal(code, stderr.String())
		}
		results, rows := decodeResults(t, stdout.Bytes()), fileSummary(t, out)
		if len(results) != 2 || len(rows) != 2 {
			t.Fatal("lost repetitions")
		}
		for i, r := range results {
			if r.Status != "completed" || r.Response == nil || r.Execution == nil || rows[i].Passed != 2 ||
				rows[i].Total != 2 || rows[i].NativeRuns != 2 || rows[i].ArtifactReused != (i == 1) || rows[i].ResponseMS <= 0 {
				t.Fatalf("row=%+v result=%s", rows[i], r.Error)
			}
			for _, filename := range []string{rows[i].ResponseFile, rows[i].GenerationFile, rows[i].RuntimeFile} {
				b, err := os.ReadFile(filepath.Join(out, filename))
				if err != nil || !json.Valid(b) {
					t.Fatal("lost original artifact", filename, err)
				}
			}
			generated, err := os.ReadFile(filepath.Join(out, strings.Replace(rows[i].GenerationFile, "-generation.json", "-generated.go", 1)))
			if err != nil || string(generated) != r.Response.Source {
				t.Fatal("changed generated bytes", err)
			}
		}
		metadata, err := os.ReadFile(filepath.Join(out, "model-retention.json"))
		if err != nil || !bytes.Contains(metadata, []byte(`"loaded":false`)) {
			t.Fatal("deterministic route loaded a model", err)
		}
		if code := RunFilesCommand(context.Background(), "files", args, io.Discard, &stderr); code != 1 {
			t.Fatal("existing output directory overwritten")
		}
	}
}

func TestFilesPreserveFiniteFailureAndNativeFailure(t *testing.T) {
	args, out := fileArgs(t, false, `{"schema":"gooo/body-runtime-cases/v1","cases":[{"input":2,"expected":999}]}`)
	var stdout, stderr bytes.Buffer
	if code := RunFilesCommand(context.Background(), "files", args, &stdout, &stderr); code != 0 {
		t.Fatal(code, stderr.String())
	}
	for _, row := range fileSummary(t, out) {
		if row.Status != "completed" || row.Passed != 0 || row.Total != 1 {
			t.Fatal("finite failure lost", row)
		}
	}
	args, out = fileArgs(t, false, `{"schema":"gooo/body-runtime-cases/v1","cases":[{"input":2,"expected":15}]}`)
	args[len(args)-1] = filepath.Join(t.TempDir(), "missing-go")
	stdout.Reset()
	if code := RunFilesCommand(context.Background(), "files", args, &stdout, &stderr); code != 1 {
		t.Fatal("native failure exit", code)
	}
	for _, row := range fileSummary(t, out) {
		if row.Status != "execution_failed" || row.GenerationFile == "" || row.RuntimeFile == "" || row.NativeRuns != 0 {
			t.Fatal("failure not retained", row)
		}
	}
}

