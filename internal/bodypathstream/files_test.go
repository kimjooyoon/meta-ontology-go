func TestFilesArgumentAndInputBounds(t *testing.T) {
	for _, tc := range []struct {
		args []string
		code int
	}{{[]string{"--help"}, 0}, {nil, 2}, {[]string{"--unknown"}, 2}} {
		var stdout, stderr bytes.Buffer
		if code := RunFilesCommand(context.Background(), "files", tc.args, &stdout, &stderr); code != tc.code || stdout.Len() != 0 {
			t.Fatal(code, stderr.String())
		}
	}
	for _, value := range []string{"0", "17"} {
		args, _ := fileArgs(t, false, "{}")
		args[11] = value
		if code := RunFilesCommand(context.Background(), "files", args, io.Discard, io.Discard); code != 2 {
			t.Fatal("unbounded repetition", code)
		}
	}
	for _, data := range [][]byte{nil, {0xff}, bytes.Repeat([]byte{'x'}, (128<<10)+1)} {
		args, out := fileArgs(t, false, "{}")
		if err := os.WriteFile(args[1], data, 0644); err != nil {
			t.Fatal(err)
		}
		if code := RunFilesCommand(context.Background(), "files", args, io.Discard, io.Discard); code != 1 {
			t.Fatal("invalid source accepted", code)
		}
		if _, err := os.Stat(out); !os.IsNotExist(err) {
			t.Fatal("invalid input created output")
		}
	}
	args, out := fileArgs(t, false, "{}")
	args[1] = t.TempDir()
	if code := RunFilesCommand(context.Background(), "files", args, io.Discard, io.Discard); code != 1 {
		t.Fatal("directory read as source", code)
	}
	if _, err := os.Stat(out); !os.IsNotExist(err) {
		t.Fatal("nonregular input created output")
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if code := RunFilesCommand(ctx, "files", args, io.Discard, io.Discard); code != 1 {
		t.Fatal("cancelled call proceeded", code)
	}
}

func TestFileOptionsExactContract(t *testing.T) {
	for _, raw := range []string{`null`, `[]`, `{"Step_attempts":1}`, `{"extra":1}`,
		`{"step_attempts":1,"step_attempts":2}`, `{}` + `{}`, strings.Repeat("[", 65) + "0" + strings.Repeat("]", 65)} {
		var options bodycodegen.TypedPathOptions
		if err := decodeFileOptions([]byte(raw), &options); err == nil {
			t.Fatal("ambiguous options accepted", raw)
		}
	}
	var options bodycodegen.TypedPathOptions
	raw := `{"step_attempts":2,"ci":{"source_sha":"` + strings.Repeat("a", 40) + `","status":"FAIL"}}`
	if err := decodeFileOptions([]byte(raw), &options); err != nil || options.StepAttempts != 2 || options.CI == nil || options.CI.Status != "FAIL" {
		t.Fatal("CI context not preserved", err)
	}
}

