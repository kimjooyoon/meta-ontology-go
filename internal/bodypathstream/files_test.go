func TestFileCancellationUnblocksOutputAndPreservesLastReport(t *testing.T) {
	line := executionLine(t, "current", `{"schema":"gooo/body-runtime-cases/v1","cases":[{"input":2,"expected":15}]}`)
	var request Request
	if err := json.Unmarshal(line, &request); err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	reader, writer := io.Pipe()
	defer reader.Close()
	defer writer.Close()
	out := t.TempDir()
	done := make(chan int, 1)
	g := fakeGenerator{generate: func(context.Context, string) (bodycodegen.Result, error) {
		return bodycodegen.Result{}, errors.New("recorded construction failure")
	}}
	go func() {
		done <- runFileRequests(ctx, g, request, 2, "", out, writer, io.Discard, func(error) int { return 1 })
	}()
	deadline := time.After(5 * time.Second)
	for {
		if _, err := os.Stat(filepath.Join(out, "summary.json")); err == nil {
			break
		}
		select {
		case <-deadline:
			t.Fatal("first report not saved before blocked output")
		case <-time.After(5 * time.Millisecond):
		}
	}
	cancel()
	select {
	case code := <-done:
		if code != 1 || len(fileSummary(t, out)) != 1 {
			t.Fatal("cancellation lost observation", code)
		}
	case <-time.After(5 * time.Second):
		t.Fatal("blocked output deadlock")
	}
}

type failedFileWriter struct{}

func (failedFileWriter) Write([]byte) (int, error) { return 0, errors.New("output unavailable") }

func TestFileOutputFailurePreservesGenerationFailure(t *testing.T) {
	line := executionLine(t, "current", `{"schema":"gooo/body-runtime-cases/v1","cases":[{"input":2,"expected":15}]}`)
	var request Request
	if err := json.Unmarshal(line, &request); err != nil {
		t.Fatal(err)
	}
	g := fakeGenerator{generate: func(context.Context, string) (bodycodegen.Result, error) {
		return bodycodegen.Result{}, errors.New("original construction failure")
	}}
	out := t.TempDir()
	if code := runFileRequests(context.Background(), g, request, 2, "", out, failedFileWriter{}, io.Discard,
		func(error) int { return 1 }); code != 1 {
		t.Fatal("output failure ignored", code)
	}
	rows := fileSummary(t, out)
	if len(rows) != 1 || rows[0].Status != "rejected" {
		t.Fatal("observation lost or next request started after output failure")
	}
	raw, err := os.ReadFile(filepath.Join(out, rows[0].ResponseFile))
	if err != nil || !bytes.Contains(raw, []byte("original construction failure")) {
		t.Fatal("original failure lost", err)
	}
}
