package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestPolicyBundleRetirementFresh1870(t *testing.T) {
	for _, name := range []string{"owned-shrink", "conflicting-part"} {
		t.Run(name, func(t *testing.T) {
			directory := t.TempDir()
			if err := writePolicy(directory, []byte("source1870-before"), policyPartsFixture1870(2)); err != nil {
				t.Fatal(err)
			}
			manifestPath := filepath.Join(directory, "policy.projection.json")
			before, err := os.ReadFile(manifestPath)
			if err != nil {
				t.Fatal(err)
			}
			part := filepath.Join(directory, "policy_part02.generated.go")
			if _, err := os.Stat(part); err != nil {
				t.Fatal("fixture did not produce two owned parts", err)
			}
			if name == "conflicting-part" {
				if err := os.WriteFile(part, []byte("caller change1870"), 0600); err != nil {
					t.Fatal(err)
				}
			}
			err = writePolicy(directory, []byte("source1870-after"), policyPartsFixture1870(1))
			if name == "conflicting-part" {
				if err == nil {
					t.Fatal("changed obsolete part was overwritten or removed")
				}
				after, err := os.ReadFile(manifestPath)
				if err != nil || !bytes.Equal(before, after) {
					t.Fatal("conflict replaced the previous manifest", err)
				}
			} else if err != nil {
				t.Fatal(err)
			} else if _, err := os.Stat(part); !os.IsNotExist(err) {
				t.Fatal("owned retired part remains", err)
			}
		})
	}
}

func policyPartsFixture1870(count int) []byte {
	var source strings.Builder
	source.WriteString("// Code generated by fixture1870; DO NOT EDIT.\npackage fixture1870\n\n")
	for index := range count {
		fmt.Fprintf(&source, "//gooo:generated:start id=\"urn:1870:%d\" kind=\"activity\"\n", index)
		fmt.Fprintf(&source, "func Slot%d() {\n", index)
		for line := range 45 {
			fmt.Fprintf(&source, "// owned layout line%d\n", line)
		}
		source.WriteString("}\n")
		fmt.Fprintf(&source, "//gooo:generated:end id=\"urn:1870:%d\" kind=\"activity\"\n\n", index)
	}
	return []byte(source.String())
}
