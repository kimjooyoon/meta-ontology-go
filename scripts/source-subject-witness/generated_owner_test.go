package main

import (
	"os"
	"path/filepath"
	"testing"
)

func generatedOwnerReport(t *testing.T) sourceReport {
	t.Helper()
	return nativeModuleReportWithSetup(t, func(root string) {
		path := filepath.Join(root, "nested", "source.go")
		raw, err := os.ReadFile(path)
		if err == nil {
			err = os.WriteFile(path, append([]byte("// Code generated by a source generator; DO NOT EDIT.\n"), raw...), 0644)
		}
		if err != nil {
			t.Fatal(err)
		}
	})
}

func TestGeneratedOwnerKeepsOriginalSourceWitness(t *testing.T) {
	report := generatedOwnerReport(t)
	ledger, err := buildLedger(report, report.CommitSHA)
	if err != nil {
		t.Fatal(err)
	}
	for _, witness := range ledger.Witnesses {
		if witness.Space == "LOGICAL_FILE" && witness.Path == "nested/source.go" {
			if !witness.GeneratorOwned || witness.Metrics[0].Value != 78 || witness.Meta.NotApplicableIndicators != 1 {
				t.Fatal(witness)
			}
			changed := witness
			changed.GeneratorOwned = false
			if sealWitness(changed).WitnessDigest == witness.WitnessDigest {
				t.Fatal("owner fact omitted from witness identity")
			}
			return
		}
	}
	t.Fatal("generated source disappeared from observations")
}

func TestGeneratedOwnerRejectsUnboundExclusions(t *testing.T) {
	for _, mutation := range []string{"missing-owner", "handwritten-owner", "wrong-rule", "wrong-reason",
		"wrong-producer", "wrong-operation", "wrong-failure-code", "blocking", "changed-lines"} {
		t.Run(mutation, func(t *testing.T) {
			report := generatedOwnerReport(t)
			for i := range report.Files {
				file := &report.Files[i]
				if file.Path == "nested/source.go" {
					if mutation == "missing-owner" {
						file.GeneratorOwned = false
					}
					if mutation == "changed-lines" {
						file.Lines++
					}
				}
				if file.Path == "root.go" && mutation == "handwritten-owner" {
					file.GeneratorOwned = true
				}
			}
			for i := range report.Meta.Indicators {
				row := &report.Meta.Indicators[i]
				if row.Subject != "nested/source.go" {
					continue
				}
				switch mutation {
				case "wrong-rule":
					row.ApplicabilityRuleID = "urn:forged:owner"
				case "wrong-reason":
					row.ApplicabilityReason = "CATALOG_APPLICABLE"
				case "wrong-producer":
					row.Producer = "unbound-scanner"
				case "wrong-operation":
					row.MetaOperation = "inspect-wrapper"
				case "wrong-failure-code":
					row.FailureCode = ""
				case "blocking":
					row.Blocking = true
				}
			}
			ledger, err := buildLedger(report, report.CommitSHA)
			if err == nil || ledger.Status != "" {
				t.Fatal("unbound exclusion accepted", mutation, err)
			}
		})
	}
}
