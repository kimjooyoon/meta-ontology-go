// Command origin-lens-codegen projects source-owned view selection.
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/kimjooyoon/meta-ontology-go/internal/bodycodegen"
	"github.com/kimjooyoon/meta-ontology-go/internal/generator"
	"github.com/kimjooyoon/meta-ontology-go/internal/projectionbundle"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: origin-lens-codegen source.gooo output-directory")
		os.Exit(2)
	}
	if err := generatePolicy(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generatePolicy(source, directory string) error {
	raw, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	var combined strings.Builder
	combined.WriteString("// Code generated by origin-lens-codegen; DO NOT EDIT.\npackage originlenspolicy\n\n")
	for _, name := range []string{"SelectLens", "SelectionReason", "LensAvailable"} {
		result, err := bodycodegen.Generate(source, raw, name)
		if err != nil {
			return err
		}
		const prefix = "package originlenspolicy\n\n"
		if !strings.HasPrefix(result.Source, prefix) || result.Report.RouteDecision.Provider != "deterministic" {
			return fmt.Errorf("policy projection requires its deterministic source package")
		}
		combined.WriteString(strings.TrimPrefix(result.Source, prefix))
		combined.WriteByte('\n')
	}
	projection, err := format.Source([]byte(combined.String()))
	if err != nil {
		return err
	}
	return writePolicy(directory, raw, projection)
}

func writePolicy(directory string, source, projection []byte) error {
	parts, err := generator.PartitionProjection(projection, 75)
	if err != nil {
		return err
	}
	manifest := projectionbundle.Manifest{Schema: projectionbundle.Schema, SourceDigest: projectionbundle.Digest(source)}
	for i, part := range parts {
		name := "policy.generated.go"
		if i > 0 {
			name = fmt.Sprintf("policy_part%02d.generated.go", i+1)
		}
		if err := os.WriteFile(filepath.Join(directory, name), part.Source, 0644); err != nil {
			return err
		}
		manifest.Members = append(manifest.Members, projectionbundle.Member{
			Path: name, Digest: projectionbundle.Digest(part.Source), RegionIDs: part.RegionIDs,
		})
	}
	raw, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(directory, "policy.projection.json"), append(raw, '\n'), 0644)
}
