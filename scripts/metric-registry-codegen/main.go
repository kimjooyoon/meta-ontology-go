// Command metric-registry-codegen projects the typed Gooo registry declaration.
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/kimjooyoon/meta-ontology-go/internal/bodycodegen"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: metric-registry-codegen source.gooo output.go")
		os.Exit(2)
	}
	if err := generate(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(sourcePath, output string) error {
	raw, err := os.ReadFile(sourcePath)
	if err != nil {
		return err
	}
	var generated strings.Builder
	generated.WriteString("// Code generated by metric-registry-codegen; DO NOT EDIT.\npackage metricprogram\n\n")
	var records []bodycodegen.RecordType
	for _, activity := range []string{"OperationAt", "OperationCount", "EntityAt", "EntityCount"} {
		projection, err := bodycodegen.Generate(sourcePath, raw, activity)
		if err != nil {
			return err
		}
		const prefix = "package metricprogram\n\n"
		if !strings.HasPrefix(projection.Source, prefix) {
			return fmt.Errorf("unexpected projection package")
		}
		generated.WriteString(strings.TrimPrefix(projection.Source, prefix))
		generated.WriteByte('\n')
		records = append(records, projection.Report.RecordTypes...)
	}
	body := generated.String()
	for _, binding := range []bridgeBinding{
		{"OperationDeclaration", "OperationSpec", "Operation", "sourceOperations", "types_program.go"},
		{"EntityDeclaration", "entitySpec", "Entity", "sourceEntities", "source.go"},
	} {
		bridge, err := renderBridge(records, binding, filepath.Dir(sourcePath))
		if err != nil {
			return err
		}
		marker := fmt.Sprintf("//gooo:generated:end id=%q kind=\"entity\"", bridge.recordID)
		if strings.Count(body, marker) != 1 {
			return fmt.Errorf("record adapter requires exactly one declared entity region")
		}
		body = strings.Replace(body, marker, bridge.code+marker, 1)
	}
	compacted, err := compactRecordLiterals([]byte(body))
	if err != nil {
		return err
	}
	formatted, err := format.Source(compacted)
	if err != nil {
		return err
	}
	return writeBundle(output, raw, formatted)
}

func writeProjection(output string, raw []byte) error {
	file, err := os.CreateTemp(filepath.Dir(output), ".metric-registry-*")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	if err := file.Chmod(0644); err != nil {
		file.Close()
		return err
	}
	if _, err := file.Write(raw); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return os.Rename(file.Name(), output)
}
