package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/kimjooyoon/meta-ontology-go/internal/meta/sourcepolicy"
)

func TestExplicitCandidateCannotRewriteGeneratedOrMixedSource(t *testing.T) {
	for _, marker := range []string{"// Code generated by a compiler; DO NOT EDIT.\n", "//gooo:generated:start id=\"urn:entry\" kind=\"library-entry\"\n"} {
		root := t.TempDir()
		source := marker + "package p\nfunc Evaluate() int {\n value := 1\n return value\n}\n"
		path := filepath.Join(root, "ordinary.go")
		if err := os.WriteFile(path, []byte(source), 0600); err != nil {
			t.Fatal(err)
		}
		c := candidate{raw: "retained-generated-candidate", source: sourcepolicy.SourceSubject{Path: "ordinary.go", Name: "Evaluate", Line: 3}}
		for _, write := range []bool{false, true} {
			if err := transformCandidate(root, c, write); err == nil || !strings.Contains(err.Error(), "owned by generated source") {
				t.Fatal("stale candidate bypassed ownership", err)
			}
		}
		after, err := os.ReadFile(path)
		if err != nil || string(after) != source {
			t.Fatal("generated bytes changed", err)
		}
	}
}
